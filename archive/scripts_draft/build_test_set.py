"""Validate test cases against the catalog and export test_set/cases.json."""
import json, glob, sys, datetime
from collections import Counter
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
catalog = yaml.safe_load((ROOT / "brand/catalog.yaml").read_text())
products = {p["id"]: p for p in catalog["products"]}
events = {e["id"]: e for e in catalog["events"]}
boutiques = {b["id"] for b in catalog["boutiques"]}

cases = []
for f in sorted(glob.glob(str(ROOT / "test_set/cases/*.yaml"))):
    cases += yaml.safe_load(open(f))

def jsonable(o):
    if isinstance(o, (datetime.date, datetime.datetime)):
        return o.isoformat()
    raise TypeError(o)

errors = []
ids = Counter(c["id"] for c in cases)
errors += [f"duplicate id {i}" for i, n in ids.items() if n > 1]
for c in cases:
    cid = c["id"]
    if c["ca"]["boutique"] not in boutiques:
        errors.append(f"{cid}: unknown boutique")
    for pid in c.get("product_ids", []):
        if pid not in products:
            errors.append(f"{cid}: unknown product {pid}")
    for eid in c.get("event_ids", []):
        if eid not in events:
            errors.append(f"{cid}: unknown event {eid}")
    for p in c["client"].get("purchases", []):
        prod = products.get(p["product"])
        if not prod:
            errors.append(f"{cid}: unknown purchased product {p['product']}")
        elif prod.get("colors") and p["color"] not in prod["colors"]:
            errors.append(f"{cid}: color {p['color']} not in {p['product']} {prod['colors']}")
    today = str(c["today"])
    for m in c["history"]:
        if m["from"] not in ("ca", "client"):
            errors.append(f"{cid}: bad sender")
        if m["time"][:10] > today:
            errors.append(f"{cid}: history after today")
    if c["scenario"] == "price_objection" and c["history"][-1]["from"] != "client":
        errors.append(f"{cid}: price objection must end with client message")

print("cases:", len(cases))
print("by scenario:", dict(Counter(c["scenario"] for c in cases)))
print("by stage:", dict(Counter(c["client"]["stage"] for c in cases)))
if errors:
    print("ERRORS:", *errors, sep="\n  ")
    sys.exit(1)
out = ROOT / "test_set/cases.json"
out.write_text(json.dumps(cases, ensure_ascii=False, indent=1, default=jsonable))
print("wrote", out.relative_to(ROOT))

# ---- human-readable index ----
SCEN = {
    "birthday_festive": "S1 生日与节日问候", "product_recommendation": "S2 产品推荐",
    "post_purchase_care": "S3 售后关怀", "reactivation": "S4 沉睡唤醒",
    "event_invitation": "S5 活动邀请", "price_objection": "S6 价格异议",
}
lines = [
    "# Test set · 50 cases",
    "",
    "All clients, CAs and conversations are fictional. Source of truth: `cases/*.yaml`; "
    "`cases.json` is generated by `scripts/build_test_set.py`; chat screenshots in `screenshots/` "
    "are rendered from the same history by `scripts/render_chats.js`.",
    "",
    "Each case's conversation history exists in two forms: **structured text** (ground truth) and a "
    "**WeChat-style screenshot** (tool input, as a CA would forward it). Comparing the tool's reading of "
    "the screenshot against the text lets us measure screenshot parsing separately from message quality.",
    "",
    "## Coverage",
    "",
    "| Scenario | Cases | 初识 | 熟悉 | 挚交 | Sparse profile |",
    "|---|---|---|---|---|---|",
]
for key, name in SCEN.items():
    cs = [c for c in cases if c["scenario"] == key]
    st = Counter(c["client"]["stage"] for c in cs)
    sparse = sum(1 for c in cs if not c["client"]["notes"])
    lines.append(f"| {name} | {len(cs)} | {st['初识']} | {st['熟悉']} | {st['挚交']} | {sparse} |")
lines += ["", "## Cases", "", "| ID | Scenario | Client | Stage | Today | Products / events | What it tests | Chat |", "|---|---|---|---|---|---|---|---|"]
for c in cases:
    refs = ", ".join(c.get("product_ids", []) + c.get("event_ids", [])) or "—"
    occ = f"（{c['occasion']}）" if c.get("occasion") else ""
    lines.append(
        f"| {c['id']} | {SCEN[c['scenario']]}{occ} | {c['client']['name']} · {c['client']['address_as']} | "
        f"{c['client']['stage']} | {c['today']} | {refs} | {c['focus']} | [png](screenshots/{c['id']}.png) |"
    )
(ROOT / "test_set/README.md").write_text("\n".join(lines) + "\n")
print("wrote test_set/README.md")
